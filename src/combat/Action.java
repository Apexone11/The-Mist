package combat;

/**
 * Constants representing possible combat actions.
 */
public class Action {
    /**
     * Standard attack action.
     */
    public static final String ATTACK = "ATTACK";
    /**
     * Defensive action to reduce incoming damage.
     */
    public static final String DEFEND = "DEFEND";
    /**
     * Action to use an item from the inventory.
     */
    public static final String USE_ITEM = "USE_ITEM";
    /**
     * Action to attempt to flee from combat.
     */
    public static final String RUN = "RUN";
}
